"""Encode the recorded real application and verify the complete demonstration video."""

import argparse
import json
from pathlib import Path
import subprocess

from fabric_inspector.common import now, read_json, sha256, write_json


def timestamp(seconds):
    milliseconds = round(seconds * 1000)
    hours, milliseconds = divmod(milliseconds, 3_600_000)
    minutes, milliseconds = divmod(milliseconds, 60_000)
    seconds, milliseconds = divmod(milliseconds, 1000)
    return f"{hours:02}:{minutes:02}:{seconds:02}.{milliseconds:03}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--verification", type=Path, default=Path("reports/application-verification/results.json")
    )
    parser.add_argument("--output", type=Path, default=Path("reports/demonstration.mp4"))
    args = parser.parse_args()
    application = read_json(args.verification)
    assert application["status"] == "PASS"
    browser = application["browser"]
    assert browser["status"] == "PASS"
    assert any(e.get("incorrect") is True for e in browser["events"])
    source = Path(browser["webm_path"])
    assert source.is_file(), "The actual browser recording is required"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_name("demonstration-encoding.mp4")
    command = [
        "ffmpeg",
        "-hide_banner",
        "-loglevel",
        "warning",
        "-y",
        "-threads",
        "1",
        "-i",
        str(source),
        "-c:v",
        "libx264",
        "-threads",
        "1",
        "-preset",
        "medium",
        "-crf",
        "22",
        "-pix_fmt",
        "yuv420p",
        "-an",
        "-movflags",
        "+faststart",
        "-metadata",
        "title=Explainable RAW-FABRID inspection",
        "-metadata",
        "comment=Actual local application screen recording; scripted browser automation and AI assistance declared.",
        str(temporary),
    ]
    subprocess.run(command, check=True)
    temporary.replace(args.output)
    probe = json.loads(
        subprocess.check_output(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_streams",
                "-show_format",
                "-of",
                "json",
                str(args.output),
            ]
        )
    )
    video = next(s for s in probe["streams"] if s["codec_type"] == "video")
    duration = float(probe["format"]["duration"])
    assert 0 < duration <= 480, duration
    assert (video["width"], video["height"]) == (1440, 1100)
    assert video["codec_name"] == "h264" and video["pix_fmt"] == "yuv420p"
    assert int(video["nb_frames"]) > 0
    assert not any(s["codec_type"] == "audio" for s in probe["streams"])
    subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-v",
            "error",
            "-xerror",
            "-threads",
            "1",
            "-i",
            str(args.output),
            "-map",
            "0:v:0",
            "-f",
            "null",
            "-",
        ],
        check=True,
    )
    events = browser["events"]
    captions = [e for e in events if "title" in e]
    subtitles = ["WEBVTT", ""]
    transcript = [
        "# Actual application demonstration",
        "",
        "Screen recording of the running local application, captured with scripted Playwright browser automation. "
        "Every displayed prediction and Grad-CAM is generated by the trained model at request time. "
        "On-screen captions are provided; this is not a recording of the student's oral defence.",
        "",
        f"Duration: {duration:.2f} seconds. Model: {application['run_id']}. Model version: `{application['model_version']}`.",
        "",
    ]
    for index, event in enumerate(captions):
        start = max(0, float(event["seconds"]))
        end = min(
            duration,
            float(captions[index + 1]["seconds"]) if index + 1 < len(captions) else duration,
        )
        if end <= start:
            continue
        subtitles.extend(
            [f"{timestamp(start)} --> {timestamp(end)}", event["title"], event["body"], ""]
        )
        transcript.extend([f"## {timestamp(start)} — {event['title']}", "", event["body"], ""])
    transcript.extend(
        [
            "## Fresh prediction events",
            "",
            "| Time | Patch | Publisher label | Model prediction | Score | Incorrect |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )
    for event in events:
        if "case_index" in event:
            transcript.append(
                f"| {timestamp(event['seconds'])} | {event['patch_id']} | {event['label']} | {event['prediction']} | {event['score']:.6f} | {event['incorrect']} |"
            )
    args.output.with_suffix(".vtt").write_text("\n".join(subtitles))
    Path("reports/demonstration-transcript.md").write_text("\n".join(transcript) + "\n")
    write_json(
        Path("reports/demonstration-metadata.json"),
        {
            "status": "PASS",
            "created_at": now(),
            "path": args.output.as_posix(),
            "duration_seconds": duration,
            "maximum_seconds": 480,
            "video_sha256": sha256(args.output),
            "bytes": args.output.stat().st_size,
            "codec": video["codec_name"],
            "pixel_format": video["pix_fmt"],
            "width": video["width"],
            "height": video["height"],
            "frames": int(video["nb_frames"]),
            "full_decode": "PASS: ffmpeg -v error -xerror decoded every video frame",
            "audio": "No narration; visible captions and separate VTT/transcript",
            "source": "Actual Playwright screen recording of the running local application",
            "source_recording_sha256": sha256(source),
            "application_verification_sha256": sha256(args.verification),
            "model_version": application["model_version"],
            "run_id": application["run_id"],
            "fresh_prediction_events": [e for e in events if "case_index" in e],
            "genuine_incorrect_prediction_shown": True,
            "scripted_automation_declared": True,
            "dataset_attribution": "Perez-Llorens, Albero-Albero and Silvestre-Blanes (2026), RAW-FABRID V1, DOI 10.17632/db6g85xsyg.1, CC BY 4.0",
            "human_oral_defence_recorded": False,
            "verification_commands": [
                command,
                "ffprobe stream/format inspection",
                "ffmpeg full-frame decode",
            ],
        },
    )
    Path("docs/demonstration-storyboard.md").write_text(
        "# Delivered demonstration\n\nThe delivered MP4 is an actual application screen recording, "
        "with fresh uploads, live predictions, Grad-CAM opacity controls, an authentic incorrect prediction, "
        "human-review limitations, invalid-input rejection and dataset attribution. The exact timed storyboard "
        "is reports/demonstration-transcript.md, and all original prediction events are in "
        "reports/application-verification/browser-results.json. This scripted recording and AI assistance "
        "are declared. It does not stand in for the student's individual live presentation.\n"
    )
    print({"video": str(args.output.resolve()), "duration_seconds": duration, "status": "PASS"})


if __name__ == "__main__":
    main()
